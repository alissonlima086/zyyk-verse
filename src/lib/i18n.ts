const catalogs: Record<Locale, Record<TranslationKey, string>> = { 'pt-BR': ptBR, en };

export const translationKeys = Object.freeze(Object.keys(ptBR)) as readonly TranslationKey[];

export function normalizeLocale(value: string | null | undefined): Locale {
  return value?.toLowerCase().startsWith('en') ? 'en' : 'pt-BR';
}

export function translate(locale: Locale, key: TranslationKey, params: TranslationParams = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
